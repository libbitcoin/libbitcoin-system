#!/usr/bin/env python3
"""
Generate the embedded cuda kernels (ptx) for libbitcoin-system.

Source: src/crypto/secp256k1/cuda/verify.cu, compiled for the device by clang
        (no cuda toolkit), then raw deflated for embedding.
Output: src/crypto/secp256k1/cuda/ptx.cpp

Run from the repository root, after a build has generated version.hpp:
  python3 tools/generate_cuda_ptx.py --boost <boost-include-directory>

On Windows the Visual Studio clang is used (C++ Clang Compiler component),
otherwise clang++ on the path, or the --clang argument.
"""

import argparse
import os
import subprocess
import sys
import tempfile
import zlib

SOURCE = os.path.join("src", "crypto", "secp256k1", "cuda", "verify.cu")
OUTPUT = os.path.join("src", "crypto", "secp256k1", "cuda", "ptx.cpp")
ARCHITECTURE = "sm_75"

